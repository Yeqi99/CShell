import assert from 'node:assert/strict';
import { selectAllMcpPermissions } from '../src/ui/components/mcp-all-permissions';
import { apiCapabilitySchema, mcpSettingsSchema, type Profile } from '../src/shared/contracts';
const id='10000000-0000-4000-8000-000000000001';
const initial=mcpSettingsSchema.parse({enabled:true,port:3777,allowedProfiles:[],allowCommands:false,capabilities:[],targetPolicies:{[id]:{allowCommands:false,capabilities:[],review:'always'}},localFileRoots:[{id,path:'C:/test',name:'test',identity:'original'}],clients:[{id,name:'client',enabled:false,allowedProfiles:[],allowCommands:false,capabilities:[],review:'always',disclosure:{mode:'full',level:'contract',budgetBytes:32768}}]});
const before=JSON.stringify(initial);
const next=selectAllMcpPermissions(initial,[{id,protocol:'client'} as Profile,{id:'20000000-0000-4000-8000-000000000002',protocol:'rdp'} as Profile],['cmd','powershell']);
mcpSettingsSchema.parse(next);
assert.equal(JSON.stringify(initial),before);
assert.deepEqual(next.allowedProfiles,[id]);
assert.deepEqual(next.capabilities,apiCapabilitySchema.options);
assert.deepEqual(next.targetPolicies,{});
assert.equal(next.review,'authorized');
assert.equal(next.localFileRoots?.[0].mutations?.length,7);
assert.equal(next.localFileRoots?.[0].identity,'original');
assert.deepEqual(next.clients?.[0].capabilities,apiCapabilitySchema.options);
assert.equal(next.clients?.[0].enabled,false);
assert.equal(next.port,3777);
assert.deepEqual(next.allowedLocalShells,['cmd','powershell']);
console.log('PASS global grants, scopes, overrides, clients, roots, immutable draft and schema');
