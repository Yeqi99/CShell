export function ClientApplication({ embedded = false }: { embedded?: boolean }) {
  const [allowHttp, setAllowHttp] = useState(false);
  const [locale, setLocale] = useState<'zh-CN' | 'en-US'>(() =>
    localStorage.getItem('client-locale') === 'en-US' ? 'en-US' : 'zh-CN',
  );
  const [view, setView] = useState<'access' | 'peers' | 'audit' | 'settings'>('access');
  const [copied, setCopied] = useState(false);
  const [password, setPassword] = useState('');
  const loaded = useRef(false);
  const [theme, setTheme] = useState(() =>
    localStorage.getItem('client-theme') === 'dark' ? 'dark' : 'light',
  );
  useEffect(() => {
    if (embedded) return;
    document.documentElement.dataset.theme = theme;
    localStorage.setItem('client-theme', theme);
    void window.cshell.clientTheme(theme as 'light' | 'dark').catch((e) => setError(e.message));
  }, [theme]);
  useEffect(() => {
    localStorage.setItem('client-locale', locale);
  }, [locale]);
  const t = words[locale];
  const [status, setStatus] = useState<ClientStatus>();
  const [interfaces, setInterfaces] = useState(['127.0.0.1']);
  const [bind, setBind] = useState('127.0.0.1'),
    [port, setPort] = useState('47831'),
    [host, setHost] = useState('127.0.0.1');
  const [shells, setShells] = useState<ClientShell[]>([]),
    [error, setError] = useState(''),
    [busy, setBusy] = useState(false);
  const refresh = async () => {
    const s = await window.cshell.clientStatus();
    setStatus(s);
    if (!loaded.current) {
      loaded.current = true;
      if (s.bind) {
        setBind(s.bind);
        setHost(s.advertisedHost ?? s.bind);
      }
      if (s.port) setPort(String(s.port));
      setShells(s.allowedShells ?? []);
      setAllowHttp(s.allowHttp ?? false);
    }
    if (s.interfaces) setInterfaces(s.interfaces);
  };
  useEffect(() => {
    void refresh().catch((e) => setError(e.message));
    const timer = setInterval(() => void refresh().catch((e) => setError(e.message)), 2000);
    return () => clearInterval(timer);
  }, []);
  const run = async (fn: () => Promise<unknown>) => {
    setBusy(true);
    setError('');
    try {
      await fn();
      await refresh();
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  };
  return (
    <div className={embedded ? 'client-app agent-embedded' : 'client-app'}>
      <header className="topbar" hidden={embedded}>
        <img className="client-brand" src={brandMark} alt="" />
        <strong>{t.title}</strong>
      </header>
      <div className="client-service-card">
        <div className="client-service-heading">
          <span className={status?.running ? 'client-led online' : 'client-led'} />
          <div>
            <h1>{status ? (status.running ? t.running : t.stopped) : t.waiting}</h1>
            <p>{status?.running ? t.ready : t.offline}</p>
          </div>
        </div>
        <button
          className={status?.running ? '' : 'client-primary'}
          disabled={busy || !status}
          onClick={() =>
            void run(async () => {
              setCopied(false);
              if (status?.running) await window.cshell.clientStop();
              else if (!status?.passwordConfigured) setView('settings');
              else
                await window.cshell.clientStart({ bind, port: Number(port), advertisedHost: host });
            })
          }
        >
          <Power size={15} />
          {busy ? t.waiting : status?.running ? t.stop : t.start}
        </button>
      </div>
      <nav className="client-nav" aria-label={t.title}>
        {(['access', 'peers', 'audit', 'settings'] as const).map((id) => (
          <button
            key={id}
            aria-current={view === id ? 'page' : undefined}
            onClick={() => setView(id)}
          >
            {t[id]}
            {id === 'peers' && !!status?.peers.length && (
              <span className="client-count">{status.peers.length}</span>
            )}
          </button>
        ))}
      </nav>
      <main className="client-page client-dashboard">
        <div hidden={view !== 'access'}>
          <section className="client-pair-card">
            <h2>{t.network}</h2>
            <p className="client-subtitle">
              {status?.passwordConfigured ? t.connectionHint : t.setupFirst}
            </p>
            <p>
              <strong>cagent</strong> · {bind}:{port}
            </p>
            {status?.running && (
              <>
                <label>
                  {t.address}
                  <input
                    value={host}
                    onChange={(e) => {
                      setHost(e.target.value);
                      setCopied(false);
                    }}
                  />
                </label>
                <button
                  className="client-primary"
                  disabled={busy}
                  onClick={() =>
                    void run(async () => {
                      await window.cshell.copyText(await window.cshell.clientConnectionInfo(host));
                      setCopied(true);
                    })
                  }
                >
                  {copied ? t.copied : t.copy}
                </button>
              </>
            )}
          </section>
          {!status?.running && (
            <button className="client-network-link" onClick={() => setView('settings')}>
              {t.network} · {bind}:{port}
            </button>
          )}
        </div>
        <section hidden={view !== 'peers'}>
          <h2>
            <ShieldCheck size={18} />
            {t.peers}
            <span className="client-count">{status?.peers.length ?? 0}</span>
          </h2>
          {!status?.peers.length && (
            <div className="client-empty">
              <Monitor size={28} />
              <strong>{t.noPeers}</strong>
              <p>{t.noPeersHint}</p>
            </div>
          )}
          {status?.peers.map((peer) => (
            <div className="client-device" key={peer.fingerprint}>
              <div>
                <strong>{peer.name}</strong>
                <span>
                  {peer.shells.map((s) => (s === 'cmd' ? 'CMD' : 'PowerShell')).join(' / ')} ·{' '}
                  {peer.connected} {t.sessions}
                </span>
                <details>
                  <summary>{t.identity}</summary>
                  <small className="client-fingerprint">{peer.fingerprint}</small>
                </details>
              </div>
              <button
                disabled={busy}
                onClick={() => void run(() => window.cshell.clientRevoke(peer.fingerprint))}
              >
                {t.revoke}
              </button>
            </div>
          ))}
        </section>

        <section className="client-activity" hidden={view !== 'audit'}>
          <h2>{t.audit}</h2>
          {!status?.audit.length && <p className="client-subtitle">{t.none}</p>}
          {status?.audit.map((a, i) => (
            <div className="client-audit" key={i}>
              <time>{new Date(a.time).toLocaleString(locale)}</time>
              <span>{t.events[a.action] ?? a.action}</span>
            </div>
          ))}
        </section>

        <section hidden={view !== 'settings'}>
          <h2>{t.network}</h2>{' '}
          <div className="client-fields">
            <label>
              {t.bind}
              <select
                disabled={status?.running || busy}
                value={bind}
                onChange={(e) => {
                  setBind(e.target.value);
                  setHost(e.target.value);
                }}
              >
                {interfaces.map((ip) => (
                  <option key={ip}>{ip}</option>
                ))}
              </select>
            </label>
            <label>
              {t.port}
              <input
                type="number"
                disabled={status?.running || busy}
                value={port}
                onChange={(e) => setPort(e.target.value)}
              />
            </label>
          </div>
          <label>
            对外地址（IP / 域名）
            <input
              value={host}
              disabled={status?.running || busy}
              onChange={(e) => setHost(e.target.value)}
            />
          </label>
          <label>
            {t.password}
            <input
              type="password"
              autoComplete="new-password"
              minLength={12}
              maxLength={128}
              value={password}
              disabled={status?.running || busy}
              onChange={(e) => setPassword(e.target.value)}
              placeholder={status?.passwordConfigured ? t.configured : ''}
            />
          </label>
          <p className="client-subtitle">{t.passwordHint}</p>
          <fieldset disabled={status?.running || busy}>
            <legend>{t.scope}</legend>
            {(['cmd', 'powershell'] as const).map((shell) => (
              <label key={shell}>
                <input
                  type="checkbox"
                  checked={shells.includes(shell)}
                  onChange={(e) =>
                    setShells(
                      e.target.checked ? [...shells, shell] : shells.filter((s) => s !== shell),
                    )
                  }
                />
                {shell === 'cmd' ? 'CMD' : 'PowerShell'}
              </label>
            ))}
          </fieldset>
          <label className="agent-http-permission">
            <input
              type="checkbox"
              checked={allowHttp}
              disabled={status?.running || busy}
              onChange={(e) => setAllowHttp(e.target.checked)}
            />
            允许通过此电脑发送 HTTP 请求
          </label>
          <p className="client-permission-note">{t.notice}</p>
          <button
            className="client-primary"
            disabled={busy || status?.running || password.length < 12 || !shells.length}
            onClick={() =>
              void run(async () => {
                await window.cshell.clientSetAccess({ password, shells, allowHttp });
                setPassword('');
                setView('access');
              })
            }
          >
            {t.saveAccess}
          </button>
          <details className="client-identity">
            <summary>{t.identity}</summary>
            <small className="client-fingerprint">SHA256 · {status?.fingerprint}</small>
          </details>
        </section>
        {error && <p role="alert">{error}</p>}
      </main>
      <footer className="client-footer" hidden={embedded}>
        <select
          aria-label="Language"
          value={locale}
          onChange={(e) => setLocale(e.target.value as typeof locale)}
        >
          <option value="zh-CN">简体中文</option>
          <option value="en-US">English</option>
        </select>

        <button
          className="icon"
          title={theme === 'light' ? t.dark : t.light}
          aria-label={theme === 'light' ? t.dark : t.light}
          onClick={() => setTheme(theme === 'light' ? 'dark' : 'light')}
        >
          {theme === 'light' ? <Moon size={16} /> : <Sun size={16} />}
        </button>
      </footer>
    </div>
  );
}
